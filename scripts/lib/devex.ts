import type { EndpointSummary } from "@sharepay/core/devex";

export const MEASURED_START = "<!-- devex:measured:start -->";
export const MEASURED_END = "<!-- devex:measured:end -->";

function cell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

export function renderMeasured(summaries: EndpointSummary[], generatedAt: string, totalEvents: number): string {
  if (totalEvents === 0) {
    return "_No API calls recorded yet. Run the checkout or the merchant with `DEVEX_EVENTS_PATH=devex/events.jsonl`, then `npm run devex:summary`._";
  }
  const lines = [
    `_Generated by \`npm run devex:summary\` at ${generatedAt} from ${totalEvents} API calls._`,
    "",
    "| Endpoint | Calls | Errors | p50 ms | p95 ms |",
    "|---|---|---|---|---|",
    ...summaries.map((s) => `| \`${cell(s.path)}\` | ${s.calls} | ${s.errors} | ${s.p50Ms} | ${s.p95Ms} |`),
  ];
  const codes = summaries.flatMap((s) => s.codes.filter((c) => c.code !== "0").map((c) => ({ path: s.path, ...c })));
  if (codes.length > 0) {
    lines.push("", "| Endpoint | Code | Count | Message |", "|---|---|---|---|");
    for (const c of codes) lines.push(`| \`${cell(c.path)}\` | ${cell(c.code)} | ${c.count} | ${cell(c.msg)} |`);
  }
  return lines.join("\n");
}

export function replaceMeasured(doc: string, section: string): string {
  const start = doc.indexOf(MEASURED_START);
  const end = doc.indexOf(MEASURED_END);
  if (start < 0 || end < start) throw new Error("DEVEX_LOG.md is missing the devex:measured markers");
  return `${doc.slice(0, start + MEASURED_START.length)}\n${section}\n${doc.slice(end)}`;
}
