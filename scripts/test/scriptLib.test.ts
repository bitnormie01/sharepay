import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { EndpointSummary } from "@sharepay/core/devex";
import { describe, expect, it } from "vitest";
import { MEASURED_END, MEASURED_START, renderMeasured, replaceMeasured } from "../lib/devex.js";
import { envValue, loadDotEnv, parseArgs, repoRoot, upsertEnvLine } from "../lib/env.js";

describe("env helpers", () => {
  it("finds the sharepay repo root from a nested folder", () => {
    const root = mkdtempSync(join(tmpdir(), "scripts-root-"));
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "sharepay" }));
    mkdirSync(join(root, "scripts", "lib"), { recursive: true });
    expect(repoRoot(join(root, "scripts", "lib"))).toBe(root);
  });

  it("loads .env into process.env when present", () => {
    const root = mkdtempSync(join(tmpdir(), "scripts-env-"));
    expect(loadDotEnv(root)).toBe(false);
    writeFileSync(join(root, ".env"), "SHAREPAY_SCRIPT_TEST_VALUE=loaded\n");
    expect(loadDotEnv(root)).toBe(true);
    expect(process.env.SHAREPAY_SCRIPT_TEST_VALUE).toBe("loaded");
  });

  it("parses commands, positionals, valued and boolean flags", () => {
    expect(parseArgs(["buy", "--stock", "NVDAB", "--usdt=2.50", "--dry-run"], new Set(["dry-run"]))).toEqual({
      command: "buy",
      positionals: [],
      flags: { stock: "NVDAB", usdt: "2.50", "dry-run": true },
    });
    expect(parseArgs(["verify", "rwa", "third-party"])).toEqual({ command: "verify", positionals: ["rwa", "third-party"], flags: {} });
    expect(parseArgs([])).toEqual({ command: null, positionals: [], flags: {} });
  });

  it("reads and upserts .env lines without touching other keys", () => {
    const text = "# comment\nBINANCE_API_KEY=abc\nBUYER_PRIVATE_KEY=\nMERCHANT_URL=\"http://localhost:9000\"\n";
    expect(envValue(text, "BINANCE_API_KEY")).toBe("abc");
    expect(envValue(text, "BUYER_PRIVATE_KEY")).toBe("");
    expect(envValue(text, "MERCHANT_URL")).toBe("http://localhost:9000");
    expect(envValue(text, "MISSING")).toBeNull();
    const updated = upsertEnvLine(text, "BUYER_PRIVATE_KEY", "0x12");
    expect(updated).toBe("# comment\nBINANCE_API_KEY=abc\nBUYER_PRIVATE_KEY=0x12\nMERCHANT_URL=\"http://localhost:9000\"\n");
    expect(upsertEnvLine("A=1\n", "B", "2")).toBe("A=1\nB=2\n");
    expect(upsertEnvLine("", "B", "2")).toBe("B=2");
  });
});

describe("DevEx measured section", () => {
  const summaries: EndpointSummary[] = [
    { path: "/api/v1/rwa/tokens", calls: 12, errors: 1, p50Ms: 180, p95Ms: 640, codes: [{ code: "0", count: 11, msg: "success" }, { code: "40304", count: 1, msg: "Access restricted | region" }] },
    { path: "/api/v1/dex/aggregator/quote", calls: 3, errors: 0, p50Ms: 220, p95Ms: 300, codes: [{ code: "0", count: 3, msg: "" }] },
  ];

  it("renders per-endpoint calls, errors, latency and the error codes", () => {
    expect(renderMeasured(summaries, "2026-10-08T10:00:00.000Z", 15)).toBe(
      [
        "_Generated by `npm run devex:summary` at 2026-10-08T10:00:00.000Z from 15 API calls._",
        "",
        "| Endpoint | Calls | Errors | p50 ms | p95 ms |",
        "|---|---|---|---|---|",
        "| `/api/v1/rwa/tokens` | 12 | 1 | 180 | 640 |",
        "| `/api/v1/dex/aggregator/quote` | 3 | 0 | 220 | 300 |",
        "",
        "| Endpoint | Code | Count | Message |",
        "|---|---|---|---|",
        "| `/api/v1/rwa/tokens` | 40304 | 1 | Access restricted \\| region |",
      ].join("\n"),
    );
    expect(renderMeasured([], "2026-10-08T10:00:00.000Z", 0)).toContain("No API calls recorded yet");
  });

  it("replaces only the text between the markers, idempotently", () => {
    const doc = `# Log\n\n${MEASURED_START}\nold\n${MEASURED_END}\n\n## Onboarding\nnotes\n`;
    const once = replaceMeasured(doc, "new table");
    expect(once).toBe(`# Log\n\n${MEASURED_START}\nnew table\n${MEASURED_END}\n\n## Onboarding\nnotes\n`);
    expect(replaceMeasured(once, "new table")).toBe(once);
    expect(() => replaceMeasured("# no markers", "x")).toThrow("devex:measured");
  });

  it("ships a DEVEX_LOG.md with the markers and the DX form's sections", () => {
    const log = readFileSync(join(repoRoot(), "DEVEX_LOG.md"), "utf8");
    expect(log).toContain(MEASURED_START);
    expect(log).toContain(MEASURED_END);
    for (const heading of [
      "## Smoke checks (day 1)",
      "## Onboarding",
      "## Documentation issues",
      "## API pitfalls",
      "## AI stack (Agentic Wallet, Agent Studio)",
      "## Tokenized-stock specifics",
      "## Redesign suggestions",
      "## Requested capabilities",
    ]) {
      expect(log).toContain(heading);
    }
  });
});
